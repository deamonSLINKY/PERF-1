/* Prints dsp/sint_tab.h: the engine's sine table (1025 points a turn, plus one), computed with the engine's own fm_sinf, so a table in
 * flash is the table the init loop made in RAM (4 KB of RAM back). Build and run: gcc -O0 -I firmware/src/dsp tools/gen_sint.c -o /tmp/gs && /tmp/gs > firmware/src/dsp/sint_tab.h */
#include <stdio.h>
#include <stdint.h>
#include "fastmath.h"
int main(void)
{
    int i;
    printf("/* generated by tools/gen_sint.c: the sine table, 1024 points a turn and one more (4100 bytes in flash instead of RAM) */\n");
    printf("static const float SINT[1025] = {\n");
    for (i = 0; i <= 1024; i++)
        printf("%s%.9ef,%s", i % 6 == 0 ? "    " : "", (double)fm_sinf((float)i * (FM_TWO_PI / 1024.0f)), i % 6 == 5 || i == 1024 ? "\n" : " ");
    printf("};\n");
    return 0;
}
