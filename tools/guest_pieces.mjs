// Guest pieces (0.17.80): pieces players shared in the Library, built in as factory pieces in the place they were made in (their genre and
// number), with their own titles. tools/guest_pieces.json holds each one's code (as the Library has it), its title for the screen (upper
// case, 16 characters at most), the full title and the maker's name. This writes firmware/src/app/guest_pieces.h.
//   node tools/guest_pieces.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, "..");
const { pcFromCode, PC_REC, PC_PRG } = await import(pathToFileURL(join(root, "web/fm1piece.js")).href);
const list = JSON.parse(readFileSync(join(here, "guest_pieces.json"), "utf8"));
const hex = (a) => Array.from(a, (v) => v).join(",");
const cstr = (s) => JSON.stringify(s).replace(/[^\x20-\x7e]/g, "");
const rows = [];
const seen = new Set();
for (const g of list) {
  const x = await pcFromCode(g.code);
  if (x.kind === "set") throw new Error(g.title + ": a set, not a piece");
  if (x.voice) throw new Error(g.title + ": it uses a DX7 voice of the player's own (not built in)");
  if (!/^[A-Z0-9 '!&.-]{1,16}$/.test(g.title)) throw new Error(g.title + ": the screen title is upper case, 16 characters at most");
  const k = x.genre * 10 + x.slot;
  if (seen.has(k)) throw new Error(g.title + ": two guest pieces in one place");
  seen.add(k);
  const kinds = x.kinds || new Uint8Array(3), fx = x.fx || new Uint8Array(9), bass = x.bass || new Uint8Array(16);
  if (x.rec.length !== PC_REC || x.prg.length !== PC_PRG || kinds.length !== 3 || fx.length !== 9 || bass.length !== 16) throw new Error(g.title + ": odd sizes");
  rows.push(`    {${x.genre}, ${x.slot}, ${x.npar}, ${cstr(g.title)}, ${cstr(g.by.toUpperCase())},   /* ${cstr(g.full).slice(1, -1)}, by ${g.by} (Library ${g.id}, ${g.added.slice(0, 10)}) */\n` +
    `     {${hex(x.rec)}},\n     {${hex(x.prg)}}, {${hex(kinds)}}, {${hex(fx)}}, {${hex(bass)}}}`);
}
const h = `/* SPDX-License-Identifier: GPL-3.0-only */
/* Generated by tools/guest_pieces.mjs from tools/guest_pieces.json: do not edit. The guest pieces (0.17.80): players' pieces from the
 * Library, built in as the factory piece of the place they were made in. Each: genre, place, how many settings its record has, its title
 * and maker for the screen, its stored record (IMG_REC bytes), progression, chord types, FILTERS / SCREAM / bass answer, bass steps. */
typedef struct {
    uint8_t genre, slot;
    uint16_t npar;
    const char *title, *by;
    uint8_t rec[${PC_REC}], prg[${PC_PRG}], kinds[3], fx[9], bass[16];
} guest_t;
#define GUEST_N ${rows.length}
static const guest_t GUEST[GUEST_N] = {
${rows.join(",\n")}
};
`;
writeFileSync(join(root, "firmware/src/app/guest_pieces.h"), h);
console.log("guest_pieces.h:", rows.length, "pieces");
