"""art/boot_dj.png (the maker's festival picture, 320 x 216) -> firmware/src/app/boot_art.h, the boot card's picture
(0.17.79): 240 x 162, sixteen colours, run-length coded a row at a time. Each byte is a run: the colour in the low 4 bits,
the run's length less one in the high 4 (1-16 pixels; a run never crosses a row). The palette ("G3", picked by eye on
2026-11-19) keeps the sun's pink, the beams' white cores and the DJ's hoodie; it is fixed here so the table is the same
every time. Also writes build/boot_art.png (the picture as the FM-1 shows it, 2x).

Needs Pillow and numpy:  python -P tools/boot_art.py"""
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art", "boot_dj.png")
OUT = os.path.join(ROOT, "firmware", "src", "app", "boot_art.h")
PREVIEW = os.path.join(ROOT, "build", "boot_art.png")
W, H = 240, 162
PAL = ("ff9ae7 e7efff 10b2ff 8475ff 523cff 0055ff 100852 0020e7 "
       "9c00ff 3900ad 000ca5 00045a 000021 007dff 73cfff ce38ff").split()
WT = np.array([0.30, 0.59, 0.11], np.float32) ** 0.5     # a rough weighting by how bright each channel looks


def main():
    img = Image.open(SRC).convert("RGB").resize((W, H), Image.LANCZOS)
    px = np.asarray(img, dtype=np.float32).reshape(-1, 3)
    raw = np.array([[int(h[i:i + 2], 16) for i in (0, 2, 4)] for h in PAL], np.int32)
    p565 = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in raw]
    shown = np.array([[(v >> 11) << 3 | (v >> 13), (v >> 5 & 63) << 2 | (v >> 9 & 3), (v & 31) << 3 | (v >> 2 & 7)]
                      for v in p565], np.float32)          # the colours as the screen shows them
    idx = (((px[:, None, :] - shown[None]) * WT) ** 2).sum(-1).argmin(1).reshape(H, W)
    data = bytearray()
    for row in idx:
        x = 0
        while x < W:
            c, n = int(row[x]), 1
            while x + n < W and n < 16 and row[x + n] == c:
                n += 1
            data.append((n - 1) << 4 | c)
            x += n
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
             "/* generated by tools/boot_art.py from art/boot_dj.png (the maker's own picture): do not edit */",
             "#define BOOT_W %d" % W, "#define BOOT_H %d" % H,
             "static const uint16_t BOOT_PAL[16] = {" + ", ".join("0x%04X" % v for v in p565) + "};",
             "static const uint8_t BOOT_RLE[%d] = {" % len(data)]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
    Image.fromarray(shown[idx].astype(np.uint8)).resize((W * 2, H * 2), Image.NEAREST).save(PREVIEW)
    print("boot_art.h: %d bytes of runs + 32 of palette" % len(data))


if __name__ == "__main__":
    sys.exit(main())
