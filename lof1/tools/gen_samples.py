"""LOF-1's built-in sampled instruments as a C header.

  python3 tools/samples/lof1_samples.py --rate 16000 --out build/samples --only UPRIGHT,...,KIT
  python3 tools/gen_samples.py build/samples/sets firmware/src/dsp/lof_samples.h

Reads each set's .json zone table and .adpcm data (4-bit IMA ADPCM, low nibble first, from predictor 0 /
index 0) and writes one byte array, a zone table and a set table. The zone's rate is the stored sample
rate / 44100 in Q16, as Felucca's sample engine takes it."""
import json
import sys
from pathlib import Path

ORDER = ["UPRIGHT", "UPRIGHT2", "VIBES", "KALIMBA", "GLOCK", "STRUM", "UPBASS", "MUTETPT", "TENORSAX", "FLUTE",
         "HARMONICA", "KIT"]


def main(src, dst):
    src = Path(src)
    data, zones, sets = bytearray(), [], []
    for name in ORDER:
        t = json.loads((src / f"{name}.json").read_text())
        blob = (src / f"{name}.adpcm").read_bytes()
        base = len(data)
        data += blob
        z0 = len(zones)
        for z in t["zones"]:
            ls, le = z["loop"] if z["loop"] else (0, 0)
            zones.append(dict(off=base + z["off"], n=z["n"], ls=ls, le=le, rate=round(t["rate"] / 44100 * 65536),
                              root=z["root"], pred=z["pred"], idx=z["idx"], lo=z["lo"], hi=z["hi"],
                              looped=1 if z["loop"] else 0))
        sets.append((name, z0, len(zones) - z0))
    L = ["/* generated by tools/gen_samples.py: LOF-1's sampled instruments, IMA ADPCM (CC0, Versilian Studios) */",
         "#pragma once", "#include <stdint.h>", "",
         "typedef struct { uint32_t off, n, ls, le, rate; float root; int16_t pred; uint8_t idx, lo, hi, looped; } smpz_t;",
         "typedef struct { uint16_t z0, nz; } smps_t;", ""]
    L.append("enum { " + ", ".join(f"SMP_{n}" for n in ORDER) + ", SMP_NSETS };")
    L.append(f"#define SMP_BYTES {len(data)}u")
    L.append("static const smps_t SMP_SET[SMP_NSETS] = {" + ", ".join(f"{{{a}, {b}}}" for _, a, b in sets) + "};")
    L.append("static const smpz_t SMP_ZONE[] = {")
    for z in zones:
        L.append(f"    {{{z['off']}u, {z['n']}u, {z['ls']}u, {z['le']}u, {z['rate']}u, {z['root']:.3f}f, {z['pred']}, "
                 f"{z['idx']}, {z['lo']}, {z['hi']}, {z['looped']}}},")
    L.append("};")
    L.append("static const uint8_t SMP_DATA[SMP_BYTES] = {")
    for i in range(0, len(data), 24):
        L.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    L.append("};")
    Path(dst).write_text("\n".join(L) + "\n")
    print(f"{dst}: {len(sets)} sets, {len(zones)} zones, {len(data)} bytes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
