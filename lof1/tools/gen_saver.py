#!/usr/bin/env python3
"""The screensaver's art (Red, nodding under the tree) into firmware/src/app/saver_art.h.

  in:  tools/art/red_lofi_frame1_240.png .. frame3 (240 x 240: the scene, head up / nod / head up)
  out: one 128-colour palette (RGB565, byte-swapped as the panel takes it), the whole scene (frame 1)
       and the head box of frames 2 and 3 (SV_HX, SV_HY, SV_HW x SV_HH), run-length coded:
         byte b < 0x80     one pixel, palette index b
         byte b >= 0x80    a run of (b & 0x7F) + 2 pixels, of the index in the next byte
"""
import os
from PIL import Image
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'firmware', 'src', 'app', 'saver_art.h')
HX, HY, HW, HH = 118, 16, 112, 112          # the head, the cup and the notes: all that changes

def rle(v):
    out, i = [], 0
    while i < len(v):
        j = i
        while j < len(v) and v[j] == v[i] and j - i < 129:
            j += 1
        n = j - i
        if n == 1:
            out.append(int(v[i]))
        else:
            out += [0x80 | (n - 2), int(v[i])]
        i = j
    return out

def main():
    fr = [Image.open(os.path.join(HERE, 'art', f'red_lofi_frame{i}_240.png')).convert('RGB') for i in (1, 2, 3)]
    strip = Image.new('RGB', (720, 240))
    for i, f in enumerate(fr):
        strip.paste(f, (i * 240, 0))
    q = strip.quantize(128, method=Image.FASTOCTREE, dither=Image.NONE, kmeans=8)
    idx = np.array(q)
    pal = q.getpalette()[:128 * 3]
    pal565 = []
    for k in range(128):
        r, g, b = pal[k * 3:k * 3 + 3]
        c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        pal565.append(((c >> 8) & 0xFF) | ((c & 0xFF) << 8))
    base = rle(idx[:, 0:240].ravel())
    heads = [rle(idx[HY:HY + HH, 240 * k + HX:240 * k + HX + HW].ravel()) for k in (1, 2)]
    def arr(name, data):
        s = f'static const uint8_t {name}[{len(data)}] = {{\n'
        for i in range(0, len(data), 24):
            s += '    ' + ', '.join(str(x) for x in data[i:i + 24]) + ',\n'
        return s + '};\n'
    with open(OUT, 'w') as f:
        f.write('/* SPDX-License-Identifier: GPL-3.0-only */\n')
        f.write('/* generated by tools/gen_saver.py: the screensaver (Red, under the tree). Art: RedtailWorks. */\n')
        f.write('#pragma once\n#include <stdint.h>\n\n')
        f.write(f'#define SV_HX {HX}\n#define SV_HY {HY}\n#define SV_HW {HW}\n#define SV_HH {HH}\n\n')
        f.write('static const uint16_t SV_PAL[128] = {\n')
        for i in range(0, 128, 12):
            f.write('    ' + ', '.join(f'0x{c:04X}' for c in pal565[i:i + 12]) + ',\n')
        f.write('};\n')
        f.write(arr('SV_SCENE', base))
        f.write(arr('SV_HEAD2', heads[0]))
        f.write(arr('SV_HEAD3', heads[1]))
    total = 256 + len(base) + sum(len(h) for h in heads)
    print(f'saver_art.h: scene {len(base)} B, heads {len(heads[0])} + {len(heads[1])} B, total {total} B')

if __name__ == '__main__':
    main()
